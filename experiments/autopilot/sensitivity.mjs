#!/usr/bin/env node
/**
 * Offline sensitivity of the pass decision to the hard-score weight and the
 * pass threshold (thesis section 3.3). Re-scores every recorded evaluation
 * (baselines and all search candidates) without calling a model:
 *
 *   s = w * assertionScore + (1 - w) * rubricScore   (rubric only if no assertions)
 *   pass = !criticalViolation && s >= t
 *
 *   node experiments/autopilot/sensitivity.mjs [--tex <dir>]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT } from './lib/api.mjs'

const RES = join(ROOT, 'results')
const texIndex = process.argv.indexOf('--tex')
const texDir = texIndex > 0 ? process.argv[texIndex + 1] : null
const read = (file) => JSON.parse(readFileSync(file, 'utf8'))

// Collect evaluations grouped by (file, trial) so that trial-level pass rates can be compared.
const trials = []
for (const goal of readdirSync(RES).filter((name) => existsSync(join(RES, name, 'design.json')))) {
    const dir = join(RES, goal)
    if (existsSync(join(dir, 'baseline.json'))) {
        read(join(dir, 'baseline.json')).repetitions.forEach((rep) =>
            trials.push({ key: `${goal}/baseline/${rep.rep}`, results: rep.devResults })
        )
    }
    for (const file of readdirSync(dir).filter((name) => /^search-.*\.json$/.test(name))) {
        read(join(dir, file)).trials.slice(1).forEach((trial) => trials.push({ key: `${goal}/${file}/${trial.id}`, results: trial.devResults || [] }))
    }
}

const evaluations = trials.flatMap((trial) => trial.results.filter((result) => result.evaluation).map((result) => result.evaluation))
const decide = (evaluation, weight, threshold) => {
    const hasAssertions = (evaluation.assertionSummary?.total || 0) > 0
    const score = hasAssertions ? weight * evaluation.assertionScore + (1 - weight) * evaluation.softScore : evaluation.softScore
    return !evaluation.criticalViolation && score >= threshold
}

const weights = [0.4, 0.5, 0.6, 0.7, 0.8]
const thresholds = [60, 70, 80]
const reference = evaluations.map((evaluation) => decide(evaluation, 0.6, 70))
const rows = []
for (const threshold of thresholds) {
    for (const weight of weights) {
        const decisions = evaluations.map((evaluation) => decide(evaluation, weight, threshold))
        const changed = decisions.filter((decision, index) => decision !== reference[index]).length
        const passRate = decisions.filter(Boolean).length / decisions.length
        rows.push({ weight, threshold, passRate, changed, changedPct: (changed / decisions.length) * 100 })
    }
}
const criticalOnly = evaluations.filter((evaluation) => evaluation.criticalViolation).length
const result = { evaluations: evaluations.length, trials: trials.length, failedByCriticalAlone: criticalOnly, rows }
writeFileSync(join(RES, 'sensitivity.json'), JSON.stringify(result, null, 2))
console.log(`${evaluations.length} evaluations, ${criticalOnly} with a critical violation`)
for (const row of rows) console.log(`t=${row.threshold} w=${row.weight}: pass ${(row.passRate * 100).toFixed(1)}%, changed ${row.changed} (${row.changedPct.toFixed(1)}%)`)

if (texDir) {
    mkdirSync(texDir, { recursive: true })
    const body = thresholds
        .map((threshold) => {
            const cells = weights.map((weight) => {
                const row = rows.find((item) => item.weight === weight && item.threshold === threshold)
                return `${(row.passRate * 100).toFixed(0)} (${row.changedPct.toFixed(0)})`
            })
            return `        $t = ${threshold}$ & ${cells.join(' & ')} \\\\`
        })
        .join('\n')
    writeFileSync(
        join(texDir, 'e1_sensitivity.tex'),
        `% Generated by experiments/autopilot/sensitivity.mjs -- do not edit by hand.\n\\begin{tabular}{l${'c'.repeat(weights.length)}}\n    \\toprule\n    & ${weights.map((weight) => `$w = ${weight}$`).join(' & ')} \\\\\n    \\midrule\n${body}\n    \\bottomrule\n\\end{tabular}%\n`
    )
    writeFileSync(
        join(texDir, 'e1_sensitivity_numbers.tex'),
        `% Generated by experiments/autopilot/sensitivity.mjs -- do not edit by hand.\n\\newcommand{\\SensEvaluations}{${evaluations.length}}%\n\\newcommand{\\SensCritical}{${criticalOnly}}%\n\\newcommand{\\SensMaxChanged}{${Math.max(...rows.map((row) => row.changedPct)).toFixed(0)}}%\n`
    )
}
